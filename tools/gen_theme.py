"""Generate QSS themes and tokens.py from design/tokens.json."""

from __future__ import annotations

import json
import re
import sys
from dataclasses import dataclass
from pathlib import Path

TEMPLATE = Path(__file__).resolve().parents[1] / "toystudio" / "app" / "theme" / "theme.qss.tmpl"
_PLACEHOLDER = re.compile(r"\{\{([A-Za-z0-9_-]+)\}\}")
_HEADER = '"""Generated by tools/gen_theme.py from design/tokens.json. Do not edit."""\n'


@dataclass(frozen=True)
class TypeStyle:
    family: str
    font_size: int
    line_height: int
    font_weight: int


@dataclass(frozen=True)
class Tokens:
    colors: dict[str, dict[str, str]]
    sizes: dict[str, int]
    type_styles: dict[str, TypeStyle]


def _px(value: str) -> int:
    return int(value.removesuffix("px"))


def load_tokens(path: Path) -> Tokens:
    data = json.loads(path.read_text("utf-8"))
    themes = [t["id"] for t in data["color"]["themes"]]
    colors = {th: {t["name"]: t["value"][th] for t in data["color"]["tokens"]} for th in themes}
    sizes = {
        t["name"]: _px(t["value"])
        for group in ("spacing", "radius", "size")
        for t in data[group]["tokens"]
    }
    families = data["type"]["families"]
    styles: dict[str, TypeStyle] = {}
    for group in data["type"]["groups"]:
        for s in group["styles"]:
            styles[s["name"]] = TypeStyle(
                families[group["family"]],
                _px(s["fontSize"]),
                _px(s["lineHeight"]),
                int(s["fontWeight"]),
            )
    return Tokens(colors, sizes, styles)


def render_qss(template: str, colors: dict[str, str], sizes: dict[str, int]) -> str:
    def repl(m: re.Match[str]) -> str:
        name = m.group(1)
        if name in colors:
            return colors[name]
        if name in sizes:
            return f"{sizes[name]}px"
        raise KeyError(name)

    return _PLACEHOLDER.sub(repl, template)


def _q(s: str) -> str:
    # Same quote choice as ruff format: double quotes unless the text contains one.
    return repr(s) if '"' in s else '"' + s + '"'


def _str_dict(name: str, d: dict[str, str]) -> str:
    rows = "".join(f"    {_q(k)}: {_q(v)},\n" for k, v in d.items())
    return f"{name}: dict[str, str] = {{\n{rows}}}\n"


def render_tokens_py(tokens: Tokens) -> str:
    sizes = "".join(f"    {_q(k)}: {v},\n" for k, v in tokens.sizes.items())
    types = "".join(
        f"    {_q(k)}: ({_q(s.family)}, {s.font_size}, {s.line_height}, {s.font_weight}),\n"
        for k, s in tokens.type_styles.items()
    )
    return (
        _HEADER
        + "\n"
        + _str_dict("DARK", tokens.colors["dark"])
        + "\n"
        + _str_dict("LIGHT", tokens.colors["light"])
        + f"\nSIZES: dict[str, int] = {{\n{sizes}}}\n"
        + "\n# name -> (family, font px, line px, weight)\n"
        + f"TYPE: dict[str, tuple[str, int, int, int]] = {{\n{types}}}\n"
    )


def _channel(v: int) -> float:
    c = v / 255
    return c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4


def _luminance(color: str) -> float:
    h = color.lstrip("#")
    r, g, b = (int(h[i : i + 2], 16) for i in (0, 2, 4))
    return 0.2126 * _channel(r) + 0.7152 * _channel(g) + 0.0722 * _channel(b)


def contrast_ratio(fg: str, bg: str) -> float:
    a, b = _luminance(fg), _luminance(bg)
    hi, lo = max(a, b), min(a, b)
    return (hi + 0.05) / (lo + 0.05)


def _write(path: Path, text: str) -> None:
    with path.open("w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def main(argv: list[str]) -> int:
    tokens_path, out_dir = Path(argv[0]), Path(argv[1])
    tokens = load_tokens(tokens_path)
    template = TEMPLATE.read_text("utf-8")
    out_dir.mkdir(parents=True, exist_ok=True)
    label = tokens.type_styles["label"]
    for theme, colors in tokens.colors.items():
        values = dict(colors)
        values["font-sans"] = tokens.type_styles["body"].family
        values["label-size"] = f"{label.font_size}px"
        values["label-weight"] = str(label.font_weight)
        qss = render_qss(template, values, tokens.sizes)
        _write(out_dir / f"theme_{theme}.qss", qss)
    _write(out_dir / "tokens.py", render_tokens_py(tokens))
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
